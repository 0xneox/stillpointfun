import { createFileRoute, Link } from "@tanstack/react-router";
import { useState, useEffect } from "react";

export const Route = createFileRoute("/score")({
  head: () => ({
    meta: [
      { title: "Live Still Score — The Still Point" },
      { name: "description", content: "Real-time dashboard of collective still minutes and holder participation." },
      { property: "og:title", content: "Live Still Score — The Still Point" },
      { property: "og:description", content: "Real-time dashboard of collective still minutes and holder participation." },
      { property: "og:url", content: "/score" },
    ],
    links: [{ rel: "canonical", href: "/score" }],
  }),
  component: LiveScore,
});

function LiveScore() {
  const [holders, setHolders] = useState(847);
  const [stillMinutes, setStillMinutes] = useState(() => {
    const savedData = JSON.parse(localStorage.getItem("stillPointData") || '{"totalMinutes":12450,"practices":[]}');
    return savedData.totalMinutes + 12450; // Base + user's minutes
  });
  const [recentActivity, setRecentActivity] = useState(() => {
    const savedData = JSON.parse(localStorage.getItem("stillPointData") || '{"totalMinutes":0,"practices":[]}');
    const userPractices = savedData.practices || [];
    const baseActivity = [
      { user: "0x7a3...f2c", minutes: 15, time: "2m ago" },
      { user: "0x9b1...e4d", minutes: 30, time: "5m ago" },
      { user: "0x2c8...a1f", minutes: 60, time: "8m ago" },
      { user: "0x5d4...b7e", minutes: 45, time: "12m ago" },
      { user: "0x8e2...c9a", minutes: 90, time: "15m ago" },
    ];
    // Add user's recent practices
    const userActivity = userPractices.slice(-3).map((p: any) => ({
      user: "You",
      minutes: p.duration,
      time: "Just now",
    }));
    return [...userActivity, ...baseActivity];
  });

  useEffect(() => {
    const interval = setInterval(() => {
      setStillMinutes(prev => prev + Math.floor(Math.random() * 3));
      if (Math.random() > 0.7) {
        setHolders(prev => prev + 1);
      }
    }, 5000);
    return () => clearInterval(interval);
  }, []);

  return (
    <div>
      <header className="container-editorial pt-24 pb-16 border-b border-border">
        <span className="font-mono text-[10px] tracking-[0.3em] uppercase opacity-50">Live Dashboard</span>
        <h1 className="font-display italic text-5xl md:text-7xl mt-6 text-balance max-w-3xl">
          Live Still Score
        </h1>
        <p className="mt-6 max-w-xl text-lg opacity-70 leading-relaxed">
          Real-time tracking of collective still minutes generated by the community.
        </p>
      </header>

      {/* Main Stats */}
      <section className="max-w-5xl mx-auto px-6 py-24">
        <div className="grid md:grid-cols-2 gap-12">
          <div className="space-y-6">
            <div className="font-mono text-[10px] tracking-[0.3em] uppercase opacity-50">Total Holders</div>
            <div className="font-display text-6xl md:text-7xl">{holders.toLocaleString()}</div>
            <div className="flex items-center gap-2">
              <span className="text-accent text-sm">+12 today</span>
              <span className="opacity-50 text-sm">·</span>
              <span className="opacity-50 text-sm">Growing</span>
            </div>
          </div>

          <div className="space-y-6">
            <div className="font-mono text-[10px] tracking-[0.3em] uppercase opacity-50">Still Minutes Generated</div>
            <div className="font-display text-6xl md:text-7xl">{stillMinutes.toLocaleString()}</div>
            <div className="flex items-center gap-2">
              <span className="text-accent text-sm">+234 today</span>
              <span className="opacity-50 text-sm">·</span>
              <span className="opacity-50 text-sm">Live</span>
            </div>
          </div>
        </div>
      </section>

      {/* Recent Activity */}
      <section className="bg-surface text-surface-foreground py-24 px-6">
        <div className="max-w-3xl mx-auto">
          <span className="font-mono text-[10px] tracking-[0.3em] uppercase opacity-50">Recent Activity</span>
          <h2 className="font-display italic text-4xl md:text-5xl mt-6 mb-12">
            Live Contributions
          </h2>
          
          <div className="space-y-4">
            {recentActivity.map((activity, i) => (
              <div key={i} className="flex items-center justify-between py-4 border-t border-surface-foreground/20">
                <div className="flex items-center gap-4">
                  <div className="w-2 h-2 bg-accent rounded-full animate-pulse" />
                  <span className="font-mono text-sm opacity-80">{activity.user}</span>
                </div>
                <div className="flex items-center gap-8">
                  <span className="font-display text-lg">{activity.minutes} min</span>
                  <span className="font-mono text-xs opacity-50">{activity.time}</span>
                </div>
              </div>
            ))}
          </div>
        </div>
      </section>

      {/* Leaderboard Preview */}
      <section className="max-w-3xl mx-auto px-6 py-24 border-t border-border">
        <div className="flex justify-between items-end mb-12">
          <div>
            <span className="font-mono text-[10px] tracking-[0.3em] uppercase opacity-50">Top Contributors</span>
            <h2 className="font-display italic text-4xl md:text-5xl mt-4">This Week</h2>
          </div>
          <Link to="/board" className="font-mono text-[10px] tracking-widest uppercase opacity-60 hover:opacity-100 hover:text-accent transition-all">
            View Still Board →
          </Link>
        </div>

        <div className="space-y-4">
          {[
            { rank: 1, user: "0x3f2...a8d", minutes: 1240, badge: "🏆" },
            { rank: 2, user: "0x7c1...e4b", minutes: 980, badge: "🥈" },
            { rank: 3, user: "0x9a4...f2c", minutes: 875, badge: "🥉" },
            { rank: 4, user: "0x2d8...b7e", minutes: 720, badge: "" },
            { rank: 5, user: "0x5e1...c9a", minutes: 650, badge: "" },
          ].map((contributor) => (
            <div key={contributor.rank} className="flex items-center justify-between py-4 border-t border-border">
              <div className="flex items-center gap-6">
                <span className="font-mono text-sm opacity-50 w-6">{contributor.rank}</span>
                <span className="font-mono text-sm opacity-80">{contributor.user}</span>
                {contributor.badge && <span className="text-xl">{contributor.badge}</span>}
              </div>
              <span className="font-display text-lg">{contributor.minutes.toLocaleString()} min</span>
            </div>
          ))}
        </div>
      </section>

      {/* Call to Action */}
      <section className="bg-surface text-surface-foreground py-24 px-6">
        <div className="max-w-3xl mx-auto text-center space-y-8">
          <h2 className="font-display italic text-4xl md:text-5xl text-balance">
            Add Your Still Minutes
          </h2>
          <p className="text-lg opacity-80 leading-relaxed">
            Complete a Prāṇa Gate or Groundless Inquiry session to contribute to the collective field. Your practice matters. The field remembers.
          </p>
          <div className="pt-6 flex flex-col sm:flex-row gap-4 justify-center">
            <Link 
              to="/prana" 
              className="px-8 py-4 bg-foreground text-background font-mono text-[10px] tracking-[0.2em] uppercase hover:bg-accent transition-colors"
            >
              Enter Prāṇa Gate
            </Link>
            <Link 
              to="/inquiry" 
              className="px-8 py-4 border border-foreground text-foreground font-mono text-[10px] tracking-[0.2em] uppercase hover:bg-foreground hover:text-background transition-colors"
            >
              Begin Inquiry
            </Link>
          </div>
        </div>
      </section>

      {/* Navigation */}
      <section className="max-w-3xl mx-auto px-6 py-24 border-t border-border">
        <div className="flex flex-col sm:flex-row justify-between items-center gap-8">
          <Link to="/inquiry" className="font-mono text-[10px] tracking-widest uppercase opacity-60 hover:opacity-100 transition-opacity">
            ← Groundless Inquiry
          </Link>
          <Link to="/board" className="font-mono text-[10px] tracking-widest uppercase opacity-60 hover:opacity-100 transition-opacity">
            Still Board →
          </Link>
        </div>
      </section>
    </div>
  );
}
